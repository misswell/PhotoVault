#!/usr/bin/env python3
"""Labelled end-to-end retrieval evaluation for PhotoVault AI search.

The other gates in this directory measure *components*: `textencoder` compares the
converted text tower against the Python reference, `search` exercises the fusion
rules against synthetic vectors, and `benchmark_siglip2.py` measures throughput.
None of them answer the question a user actually cares about -- "when I type this,
does the right photo come back first?" -- because that needs a photo library with
*known* contents.

This closes that gap. It parses the `eval|` lines the app's self-check emits (each
carries the ranking with every asset's original filename) and joins them against
the labels below.

Setup, once, against a booted simulator:

    python3 tools/models/make_eval_fixture.py --output /tmp/evalset
    xcrun simctl addmedia <simulator-udid> /tmp/evalset/*.jpg
    # in the app: launch with --pv-ai-selfcheck --pv-ai-selfcheck-index
    # then pull Library/Caches/PhotoVault/AISearchSelfCheck.log out of the
    # app's data container and pass it here.

`PHAssetResource.originalFilename` preserves the name the file was imported under,
so the filenames in the log are the generated ones and the join is exact. (The
Photos database's own `ZFILENAME` renames them to `IMG_nnnn.JPG`, and `addmedia`
reorders the batch -- so neither the DB name nor the import order can be used as
the label. Both were checked.)

Scope, stated plainly: this is a **simulator fixture of rendered images**, not a
device claim and not a substitute for a real photo library. It is strong evidence
that the full chain -- PhotoKit -> vision tower -> embedding matrix -> query
analysis -> fusion -> ranking -- puts the right asset first, and it is the only
measurement here that does. Absolute scores are not comparable to a real library's.

Usage:
    python3 tools/models/eval_retrieval.py <path-to-AISearchSelfCheck.log>
    python3 tools/models/eval_retrieval.py <log> --require-recall 1.0
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Ground truth
# ---------------------------------------------------------------------------

# Generated by make_eval_fixture.py. The filename is the label.
COLOUR_FIXTURE = {
    "photo0.jpg": "red",
    "photo1.jpg": "green",
    "photo2.jpg": "blue",
    "photo3.jpg": "yellow",
    "photo4.jpg": "purple",
    "photo5.jpg": "cyan",
    "exiftest.jpg": "red",
}

# Rendered words. These are answered by the OCR pathway, not by appearance, so
# they also prove OCR text reaches and influences the ranking.
TEXT_FIXTURE = {
    "invoice.jpg": "invoice",
    "passport.jpg": "passport",
}

# query -> the filenames that are genuinely correct answers.
QUERIES: dict[str, set[str]] = {
    **{f"a {label} image": {name for name, lab in COLOUR_FIXTURE.items() if lab == label}
       for label in sorted(set(COLOUR_FIXTURE.values()))},
    **{f"an {word}": {name} for name, word in TEXT_FIXTURE.items() if word[0] in "aeiou"},
    **{f"a {word}": {name} for name, word in TEXT_FIXTURE.items() if word[0] not in "aeiou"},
    # Quoted text is an exact-text (OCR) request. These are the queries that
    # actually reach the OCR pathway; the unquoted ones above are answered by
    # appearance, which is why both are kept.
    **{f'"{word.upper()}"': {name} for name, word in TEXT_FIXTURE.items()},
}

# Filenames that are correct answers but are NOT part of this fixture (Apple's
# stock photos). Any of them appearing is neither credited nor penalised -- it is
# simply unlabelled, and silently counting it as a miss would understate quality.
def _is_labelled(name: str) -> bool:
    return name in COLOUR_FIXTURE or name in TEXT_FIXTURE


# Set-logic checks. These assert *structure* -- what got included or excluded --
# because the correct outcome is not "one right answer" but a relationship.
# `combine` and `neg` are asserted against the analyzer's own plan, so a ranking
# that merely looks right for the wrong reason still fails.
SET_LOGIC = [
    {
        "query": "a red image or a green image",
        "combine": "any",
        "neg": 0,
        "require_present": ["photo0.jpg", "photo1.jpg"],
        "why": "OR fuses with max, so both colours must survive",
    },
    {
        "query": "a red image and a blue image",
        "combine": "all",
        "neg": 0,
        "require_top_below": 0.10,
        "why": "nothing is both red and blue, so AND's min fusion must stay unconvinced",
    },
    {
        "query": "a red image not a cyan image",
        "combine": "all",
        "neg": 1,
        "require_absent": ["photo5.jpg"],
        "require_present": ["photo0.jpg"],
        "why": "the negative clause must reject the cyan photo",
    },
]

# Metadata-filter checks. These never touch the vector path, so they cover the
# other half of the engine: the offline gazetteer resolving a place name to a
# coordinate, and the date parser producing a range. Each location fixture image
# carries GPS EXIF chosen for a different city, so a query that resolves the wrong
# city finds nothing rather than finding something plausible.
METADATA_CHECKS = [
    {"query": "北京", "expect": ["gpstest.jpg"], "near": (39.9042, 116.4074)},
    {"query": "上海", "expect": ["shanghai.jpg"], "near": (31.2304, 121.4737)},
    {"query": "东京", "expect": ["tokyo.jpg"], "near": (35.6762, 139.6503)},
]

# Every asset imported in the same batch shares this capture date, so the filter
# must return a contiguous set rather than a single asset.
DATE_CHECK = {"query": "2026年9月14日", "date": "2026-09-14", "minimum": 3}

# Similar-image search: each seed's nearest neighbour is known, because the
# fixture is built from flat colours and rendered pages. The seed must not appear
# in its own results -- returning the query image as its own best match is the
# classic way this feature looks broken while appearing to work.
SIMILAR_CHECKS = [
    {"seed": "photo0.jpg", "expect_top": "exiftest.jpg", "why": "red's nearest neighbour is the other red"},
    {"seed": "photo5.jpg", "expect_top": "photo2.jpg", "why": "cyan's nearest neighbour is blue"},
    {"seed": "invoice.jpg", "expect_top": "passport.jpg", "why": "a page of text resembles the other page of text"},
]

SIMILAR = re.compile(r"^similar\|(?P<seed>[^|]+)\|(?P<rest>.*)$")


def parse_similar(log_text: str) -> dict[str, list[tuple[str, float]]]:
    out: dict[str, list[tuple[str, float]]] = {}
    for line in log_text.splitlines():
        m = SIMILAR.match(line.strip())
        if not m:
            continue
        hits: list[tuple[str, float]] = []
        for token in m.group("rest").split():
            if ":" not in token:
                continue
            name, _, score = token.rpartition(":")
            try:
                hits.append((name, float(score)))
            except ValueError:
                continue
        out[m.group("seed")] = hits
    return out


META = re.compile(r"^evalmeta\|(?P<query>[^|]+)\|(?P<name>[^|]+)\|(?P<rest>.*)$")


def parse_meta(log_text: str) -> dict[str, list[tuple[str, str, str, str]]]:
    """Parse `evalmeta|<query>|<name>|<lat>,<lon>,<date>` into per-query rows."""
    out: dict[str, list[tuple[str, str, str, str]]] = {}
    for line in log_text.splitlines():
        m = META.match(line.strip())
        if not m:
            continue
        lat, _, remainder = m.group("rest").partition(",")
        lon, _, date = remainder.partition(",")
        out.setdefault(m.group("query"), []).append((m.group("name"), lat, lon, date))
    return out


LINE = re.compile(r"^eval\|(?P<query>[^|]+)\|(?P<rest>.*)$")
PLAN = re.compile(r"^evalplan\|(?P<query>[^|]+)\|(?P<rest>.*)$")


def parse_plans(log_text: str) -> dict[str, dict[str, str]]:
    """Parse `evalplan|query|candidates=N|ocr=...|clauses=N|combine=x|neg=N`.

    Needed because a set-logic query can produce a plausible-looking ranking for
    the wrong reason. Confirming the analyzer actually parsed `not` as a negative
    clause is a different claim from the ranking merely looking right.
    """
    plans: dict[str, dict[str, str]] = {}
    for line in log_text.splitlines():
        m = PLAN.match(line.strip())
        if not m:
            continue
        fields: dict[str, str] = {}
        for token in m.group("rest").split("|"):
            key, _, value = token.partition("=")
            fields[key] = value
        plans[m.group("query")] = fields
    return plans


def parse(log_text: str) -> dict[str, list[tuple[str, float]]]:
    """Pull `eval|<query>|<name>:<score> ...` lines out of the self-check log."""
    rankings: dict[str, list[tuple[str, float]]] = {}
    for line in log_text.splitlines():
        m = LINE.match(line.strip())
        if not m:
            continue
        hits: list[tuple[str, float]] = []
        for token in m.group("rest").split():
            if ":" not in token:
                continue
            name, _, score = token.rpartition(":")
            try:
                hits.append((name, float(score)))
            except ValueError:
                continue
        rankings[m.group("query")] = hits
    return rankings


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("log", type=Path)
    ap.add_argument(
        "--require-recall",
        type=float,
        default=None,
        help="exit non-zero unless every query achieves at least this Recall@k",
    )
    ap.add_argument(
        "--require-precision",
        type=float,
        default=None,
        help=(
            "exit non-zero unless Precision@1 reaches this. Recall@k alone cannot "
            "catch an ordering regression: moving a correct answer from rank 1 to "
            "rank 6 leaves recall untouched but is exactly the failure a user sees."
        ),
    )
    args = ap.parse_args()

    if not args.log.exists():
        print(f"no such log: {args.log}", file=sys.stderr)
        return 2

    rankings = parse(args.log.read_text(errors="replace"))
    if not rankings:
        print(
            "no eval| lines found. Launch the app with "
            "--pv-ai-selfcheck --pv-ai-selfcheck-index.",
            file=sys.stderr,
        )
        return 2

    print(f"{'query':<20} {'P@1':>5} {'R@k':>6} {'RR':>6}  top hit")
    print("-" * 72)

    checks = 0
    passes = 0
    reciprocal_ranks: list[float] = []
    p1_hits = 0
    recall_failures: list[str] = []

    for query, expected in QUERIES.items():
        hits = rankings.get(query)
        if hits is None:
            print(f"{query:<20} {'--':>5} {'--':>6} {'--':>6}  (not in log)")
            continue

        checks += 1
        names = [name for name, _ in hits]

        # Precision@1: is the top result a correct answer?
        p1 = 1.0 if names and names[0] in expected else 0.0
        p1_hits += int(p1)

        # Recall@k: how many of the correct answers appear anywhere in the list.
        found = sum(1 for n in names if n in expected)
        recall = found / len(expected) if expected else 0.0

        # Reciprocal rank of the first correct answer.
        rr = 0.0
        for i, n in enumerate(names, start=1):
            if n in expected:
                rr = 1.0 / i
                break
        reciprocal_ranks.append(rr)

        top = names[0] if names else "-"
        top_score = hits[0][1] if hits else 0.0
        mark = "ok " if p1 else "MISS"
        print(f"{query:<20} {p1:>5.2f} {recall:>6.2f} {rr:>6.2f}  {mark} {top} ({top_score:.4f})")

        if p1:
            passes += 1
        if args.require_recall is not None and recall + 1e-9 < args.require_recall:
            recall_failures.append(f"{query} R@k={recall:.2f}")

    if not checks:
        print("\nno labelled query in the log matched this fixture", file=sys.stderr)
        return 2

    mrr = sum(reciprocal_ranks) / len(reciprocal_ranks)
    print("-" * 72)
    print(f"labelled queries   {checks}")
    print(f"precision@1        {p1_hits}/{checks} = {p1_hits / checks:.4f}")
    print(f"MRR                {mrr:.4f}")

    failed = False

    # ---- set logic --------------------------------------------------------
    plans = parse_plans(args.log.read_text(errors="replace"))
    print()
    print("set logic")
    print("-" * 72)
    for check in SET_LOGIC:
        query = check["query"]
        names = [n for n, _ in rankings.get(query, [])]
        scores = [sc for _, sc in rankings.get(query, [])]
        plan = plans.get(query, {})
        problems: list[str] = []

        if not names:
            problems.append("no results in log")
        if plan.get("combine") != check["combine"]:
            problems.append(f"combine={plan.get('combine')!r} expected {check['combine']!r}")
        if plan.get("neg") != str(check["neg"]):
            problems.append(f"neg={plan.get('neg')!r} expected {check['neg']}")
        for want in check.get("require_present", []):
            if want not in names:
                problems.append(f"missing {want}")
        for unwanted in check.get("require_absent", []):
            if unwanted in names:
                problems.append(f"{unwanted} should have been rejected")
        limit = check.get("require_top_below")
        if limit is not None and scores and scores[0] >= limit:
            problems.append(f"top score {scores[0]:.4f} >= {limit} (too confident)")

        status = "ok " if not problems else "FAIL"
        print(f"{query:<34} {status} {check['why']}")
        for problem in problems:
            print(f"{'':<34}      - {problem}")
            failed = True

    # ---- metadata filters -------------------------------------------------
    meta = parse_meta(args.log.read_text(errors="replace"))
    print()
    print("metadata filters")
    print("-" * 72)
    for check in METADATA_CHECKS:
        query = check["query"]
        rows = meta.get(query, [])
        names = [r[0] for r in rows]
        problems: list[str] = []
        if names != check["expect"]:
            problems.append(f"got {names or 'nothing'}, expected {check['expect']}")
        for name, lat, lon, _ in rows:
            try:
                dlat = abs(float(lat) - check["near"][0])
                dlon = abs(float(lon) - check["near"][1])
            except ValueError:
                problems.append(f"{name}: missing coordinate ({lat},{lon})")
                continue
            if dlat > 0.01 or dlon > 0.01:
                problems.append(
                    f"{name}: {lat},{lon} is {dlat:.3f},{dlon:.3f} from the expected city"
                )
            print(f"{query:<34} {'ok ' if not problems else 'FAIL'} {name} @ {lat},{lon}")
        if not rows:
            print(f"{query:<34} FAIL no results")
        for problem in problems:
            print(f"{'':<34}      - {problem}")
            failed = True

    rows = meta.get(DATE_CHECK["query"], [])
    wrong = [r for r in rows if r[3] != DATE_CHECK["date"]]
    enough = len(rows) >= DATE_CHECK["minimum"]
    ok = enough and not wrong
    summary = (
        f"{len(rows)} results, all on {DATE_CHECK['date']}"
        if ok
        else f"{len(rows)} results, expected >= {DATE_CHECK['minimum']} all on {DATE_CHECK['date']}"
    )
    print(f"{DATE_CHECK['query']:<34} {'ok ' if ok else 'FAIL'} {summary}")
    if not enough:
        print(f"{'':<34}      - only {len(rows)}, expected at least {DATE_CHECK['minimum']}")
        failed = True
    for name, _, _, date in wrong:
        print(f"{'':<34}      - {name} is dated {date}, outside the requested range")
        failed = True

    # ---- similar image ----------------------------------------------------
    similar = parse_similar(args.log.read_text(errors="replace"))
    print()
    print("similar image")
    print("-" * 72)
    for check in SIMILAR_CHECKS:
        seed = check["seed"]
        hits = similar.get(seed)
        problems: list[str] = []
        if hits is None:
            problems.append("no results in log")
            names: list[str] = []
        else:
            names = [n for n, _ in hits]
            if names and names[0] != check["expect_top"]:
                problems.append(f"top is {names[0]}, expected {check['expect_top']}")
            if seed in names:
                problems.append(f"the seed {seed} returned itself")
        top = f"{names[0]} ({hits[0][1]:.4f})" if hits else "-"
        print(f"{seed:<16} -> {top:<28} {'ok ' if not problems else 'FAIL'} {check['why']}")
        for problem in problems:
            print(f"{'':<16}    - {problem}")
            failed = True

    if args.require_recall is not None:
        if recall_failures:
            print(f"\nFAIL: Recall@k below {args.require_recall}: {', '.join(recall_failures)}")
            failed = True
        else:
            print(f"RESULT: every query met Recall@k >= {args.require_recall}")

    precision = p1_hits / checks
    if args.require_precision is not None:
        if precision + 1e-9 < args.require_precision:
            print(
                f"FAIL: Precision@1 {precision:.4f} below required "
                f"{args.require_precision}"
            )
            failed = True
        else:
            print(f"RESULT: Precision@1 {precision:.4f} >= {args.require_precision}")

    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
